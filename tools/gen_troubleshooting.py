#!/usr/bin/env python3
"""Writes the generated parts of docs/troubleshooting.md from the plugin's own source, so the wording cannot drift.

    python tools/gen_troubleshooting.py            rewrite the generated blocks in docs/troubleshooting.md
    python tools/gen_troubleshooting.py --check    exit 1 if the file is out of date (nothing is written)
    add --doc PATH to work on another copy of the page (the self-check does, for its control)

Two blocks are generated, between marker comments:
  ai-rows      one row per AiError, the message text from src/Soundstage/Ai/AiMessages.cs and the cause from the
               doc comment on the enum member in src/Soundstage/Ai/AiError.cs
  intake-rows  the photo intake refusals from src/Soundstage/Ai/PhotoToScene/Intake.cs
Everything else in the file is written by hand.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "troubleshooting.md"
AI_ERROR = ROOT / "src" / "Soundstage" / "Ai" / "AiError.cs"
AI_MESSAGES = ROOT / "src" / "Soundstage" / "Ai" / "AiMessages.cs"
INTAKE = ROOT / "src" / "Soundstage" / "Ai" / "PhotoToScene" / "Intake.cs"


def block(name: str) -> tuple[str, str]:
    return f"<!-- {name}:start (generated by tools/gen_troubleshooting.py, do not edit) -->", f"<!-- {name}:end -->"


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def clean_message(text: str) -> str:
    # The code fills in the provider's name; the doc says "the provider" so one row fits every provider.
    text = text.replace("{providerName}", "the provider")
    text = re.sub(r"\s+", " ", text)
    return text[:1].upper() + text[1:]


def ai_rows() -> str:
    enum_text = AI_ERROR.read_text(encoding="utf-8")
    body = enum_text[enum_text.index("public enum AiError"):]
    body = body[:body.index("\n}")]
    causes: dict[str, str] = {}
    for m in re.finditer(r"/// <summary>(.*?)</summary>\s*\n\s*(\w+),", body, re.S):
        causes[m.group(2)] = re.sub(r"\s+", " ", re.sub(r"///", "", m.group(1))).strip()

    msgs: dict[str, str] = {}
    for m in re.finditer(r'AiError\.(\w+)\s*=>\s*\$?"((?:[^"\\]|\\.)*)"', AI_MESSAGES.read_text(encoding="utf-8")):
        msgs[m.group(1)] = clean_message(m.group(2))

    order = [n for n in re.findall(r"^\s*(\w+),\s*$", body, re.M) if n in msgs]
    missing = [n for n in causes if n not in msgs]
    if missing:
        raise SystemExit(f"AiMessages.cs has no message for: {', '.join(missing)}")
    lines = ["| What you see on the AI tab | Why |", "|---|---|"]
    for name in order:
        lines.append(f"| {cell(msgs[name])} | {cell(causes.get(name, ''))} |")
    return "\n".join(lines)


def intake_rows() -> str:
    text = INTAKE.read_text(encoding="utf-8")
    rows = []
    seen = set()
    for m in re.finditer(r'Fail\(IntakeError\.(\w+),\s*\$?"((?:[^"\\]|\\.)*)"\)', text):
        msg = re.sub(r"\{[^}]*\}", "N", m.group(2))
        if (m.group(1), msg) in seen:
            continue
        seen.add((m.group(1), msg))
        rows.append(f"| {cell(msg)} | {m.group(1)} |")
    if not rows:
        raise SystemExit("found no intake messages in Intake.cs")
    return "\n".join(["| What you see on the Photo tab | Class |", "|---|---|", *rows])


def render(doc: str) -> str:
    for name, make in (("ai-rows", ai_rows), ("intake-rows", intake_rows)):
        start, end = block(name)
        if start not in doc or end not in doc:
            raise SystemExit(f"{DOC.name} is missing the {name} markers")
        head, rest = doc.split(start, 1)
        _, tail = rest.split(end, 1)
        doc = head + start + "\n" + make() + "\n" + end + tail
    return doc


def main() -> int:
    global DOC
    if "--doc" in sys.argv:
        DOC = Path(sys.argv[sys.argv.index("--doc") + 1])
    current = DOC.read_text(encoding="utf-8")
    updated = render(current)
    if "--check" in sys.argv:
        if updated != current:
            print("docs/troubleshooting.md is out of date: run python tools/gen_troubleshooting.py")
            return 1
        print("docs/troubleshooting.md is up to date")
        return 0
    if updated != current:
        DOC.write_text(updated, encoding="utf-8", newline="\n")
        print("docs/troubleshooting.md updated")
    else:
        print("docs/troubleshooting.md already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
